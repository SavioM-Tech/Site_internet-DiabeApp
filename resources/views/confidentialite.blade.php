                <h2>1. Introduction</h2>
                <p>Diabe-APP est une application mobile de suivi et d'éducation pour les personnes diabétiques,
                    développée par Savio Milandou. Cette politique de confidentialité explique comment nous traitons
                    vos données.</p>

                <h2>2. Données collectées</h2>
                <p>Diabe-APP collecte et stocke les données suivantes <strong>uniquement sur votre appareil</strong> :</p>
                <ul>
                    <li><strong>Profil personnel</strong> : prénom, nom, date de naissance, photo de profil, genre</li>
                    <li><strong>Données de santé</strong> : mesures glycémiques, mesures de tension artérielle, calculs
                        IMC</li>
                    <li><strong>Médicaments et rappels</strong> : noms des médicaments, horaires de prise, doses</li>
                    <li><strong>Contacts d'urgence</strong> : noms et numéros de téléphone</li>
                    <li><strong>Préférences</strong> : langue, unité de glycémie, objectifs glycémiques</li>
                </ul>

                <h2>3. Stockage des données</h2>
                <div class="legal-callout">
                    <p style="margin:0;"><strong>Toutes vos données sont stockées localement sur votre appareil.</strong>
                        Diabe-APP ne dispose d'aucun serveur, ne transmet aucune donnée à des tiers et ne nécessite
                        aucune connexion internet pour fonctionner.</p>
                </div>
                <p>Vos données ne quittent jamais votre téléphone, sauf si vous utilisez la fonction d'export PDF (qui
                    génère un fichier local que vous partagez vous-même).</p>

                <h2>4. Partage des données</h2>
                <p>Nous ne partageons, ne vendons et ne transmettons aucune donnée personnelle à des tiers.</p>

                <h2>5. Permissions utilisées</h2>
                <ul>
                    <li><strong>Notifications</strong> : pour les rappels de médicaments</li>
                    <li><strong>Caméra / Galerie photos</strong> : pour la photo de profil uniquement</li>
                    <li><strong>Vibration</strong> : pour les retours haptiques</li>
                </ul>

                <h2>6. Données de santé</h2>
                <p>Les informations de santé affichées dans l'application sont fournies à titre <strong>éducatif et
                        informatif uniquement</strong>. Elles ne remplacent pas un avis médical professionnel. Consultez
                    toujours votre médecin pour toute décision médicale.</p>

                <h2>7. Suppression des données</h2>
                <p>Vous pouvez supprimer toutes vos données à tout moment en désinstallant l'application. Aucune donnée
                    n'est conservée après désinstallation.</p>

                <h2>8. Enfants</h2>
                <p>Cette application n'est pas destinée aux enfants de moins de 13 ans.</p>

                <h2>9. Contact</h2>
                <p>Pour toute question concernant cette politique de confidentialité :</p>
                <ul>
                    <li><strong>Email</strong> : <a href="mailto:support@diabeapp.com">support@diabeapp.com</a></li>
                    <li><strong>Téléphone</strong> : 06 41 00 36 86</li>
                </ul>

                <h2>10. Modifications</h2>
                <p>Nous nous réservons le droit de modifier cette politique. Toute modification sera notifiée via une
                    mise à jour de l'application.</p>
